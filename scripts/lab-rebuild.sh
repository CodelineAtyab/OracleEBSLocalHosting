#!/usr/bin/env bash
# lab-rebuild.sh — build the whole lab from the templates on a (re)built host:
# class + N student sandboxes + N client VMs + Proxmox users + class EBS logins.
#
#   scripts/lab-rebuild.sh [N]        # default N = 9
#
# This REGENERATES scripts/inventory.conf (keeping only the class row) before
# adding students, so it is meant for a clean build (fresh host or full reset),
# not for incrementally adding students to a populated lab (use add-students.sh).
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
# shellcheck disable=SC1091
source "$HERE/lib.sh"

N="${1:-9}"
CLASS_IP="${CLASS_IP:-192.168.100.223}"

qm config 9000 >/dev/null 2>&1 || { echo "ERROR: golden template 9000 missing — restore it first"; exit 1; }
qm config 9200 >/dev/null 2>&1 || { echo "ERROR: client template 9200 missing — restore it first"; exit 1; }

echo "== lab-rebuild: class + $N students =="
# canonical inventory (class only); students are appended by add-students.sh
cp -a "$INVENTORY" "$INVENTORY.$(date +%s).bak" 2>/dev/null || true
cat > "$INVENTORY" <<EOF
# EBS lab inventory — "<vmid> <name> <role> <ip>"
# Regenerated by lab-rebuild.sh $(date +%F). Keep IPs in sync with each guest /etc/hosts.
9010  ebs1213-class   ebs     $CLASS_IP
EOF

"$HERE/create-class.sh" "$CLASS_IP"
"$HERE/add-students.sh" "$N"
"$HERE/sync-acls.sh"
"$HERE/create-class-users.sh"
"$HERE/lab-status.sh"
